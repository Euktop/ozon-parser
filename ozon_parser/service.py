"""Установка автозапуска ozon-parser в системный менеджер сервисов.

Платформенные механизмы:

- Windows: Startup folder + `.vbs`. Файл
  `%APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\Startup\\ozon-parser-{mode}.vbs`
  запускает `python -m ozon_parser {mode}` через `WScript.Shell.Run(..., 0, False)` —
  **скрытое окно, без прав администратора**. schtasks не используется: `
  schtasks /create /sc onlogon` уходит в системный Task Scheduler Library и
  требует elevation. Startup folder — user-level, работает всегда.
- macOS:   launchd, plist в `~/Library/LaunchAgents/com.ozon-parser.{mode}.plist`,
  `RunAtLoad=true`, `KeepAlive=true`. Загружается через `launchctl load`.
- Linux:   systemd --user, unit в `~/.config/systemd/user/ozon-parser-{mode}.service`,
  `Restart=on-failure`. Активируется через `systemctl --user enable --now`.

`mode`:

- `serve` — HTTP-приём (bookmarklet, extension). Порт берётся из конфига
  или переопределяется через `--port`.
- `daemon` — фоновый опрос клипборда. Интервал берётся из конфига
  или переопределяется через `--interval`.

Идемпотентность: повторный `install` перезаписывает unit/task/plist/vbs.
`uninstall` безопасен, если сервиса нет — вернёт `ok=True, missing=True`.

Ограничение Windows: Startup folder не перезапускает упавший процесс.
Для restart-on-crash нужен Task Scheduler с админ-правами (см. README).
"""

from __future__ import annotations

import json
import logging
import os
import subprocess
import sys
import urllib.request
from dataclasses import dataclass
from pathlib import Path

LOG = logging.getLogger("ozon_parser.service")

VALID_MODES = ("serve", "daemon")


@dataclass
class InstallResult:
    ok: bool
    mode: str
    kind: str  # "startup-vbs" | "launchd" | "systemd"
    location: str
    message: str


@dataclass
class UninstallResult:
    ok: bool
    mode: str
    missing: bool
    message: str


@dataclass
class StatusResult:
    mode: str
    installed: bool
    running: bool
    message: str


# ============================================================================
#  helpers
# ============================================================================


def _validate_mode(mode: str) -> None:
    if mode not in VALID_MODES:
        raise ValueError(f"mode must be one of {VALID_MODES}, got {mode!r}")


def _python_and_args(
    mode: str,
    *,
    port: int | None,
    interval: float | None,
    log_file: Path | str | None = None,
) -> list[str]:
    """Команда запуска сервиса.

    В dev-режиме: ``<python> -m ozon_parser <mode>``.
    В frozen (PyInstaller): ``<ozon-parser.exe> <mode>`` — нельзя передавать
    ``-m ozon_parser`` уже собранному exe, он это не поймёт.
    """
    if getattr(sys, "frozen", False):
        args: list[str] = [sys.executable, mode]
    else:
        args = [sys.executable, "-m", "ozon_parser", mode]
    if mode == "serve":
        if port is not None:
            args.extend(["--port", str(int(port))])
    else:  # daemon
        args.append("--quiet")
        if interval is not None:
            args.extend(["--interval", str(float(interval))])
    if log_file is not None:
        args.extend(["--log-file", str(log_file)])
    return args


def _run(cmd: list[str]) -> subprocess.CompletedProcess:
    LOG.debug("run: %s", cmd)
    try:
        return subprocess.run(cmd, capture_output=True, text=True)
    except FileNotFoundError as e:
        LOG.warning("command not found: %s (%s)", cmd[0], e)
        return subprocess.CompletedProcess(cmd, 127, stdout="", stderr=str(e))
    except OSError as e:
        LOG.warning("failed to run %s: %s", cmd[0], e)
        return subprocess.CompletedProcess(cmd, 126, stdout="", stderr=str(e))


# ============================================================================
#  Windows: Startup folder + .vbs (без администратора)
# ============================================================================


def _win_startup_dir() -> Path:
    appdata = os.environ.get("APPDATA")
    base = Path(appdata) if appdata else (Path.home() / "AppData" / "Roaming")
    return base / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"


def _win_vbs_path(mode: str) -> Path:
    return _win_startup_dir() / f"ozon-parser-{mode}.vbs"


def _win_vbs_content(
    mode: str,
    *,
    port: int | None,
    interval: float | None,
    log_file: Path | str | None = None,
) -> str:
    args = _python_and_args(mode, port=port, interval=interval, log_file=log_file)
    # Квотируем элементы с пробелами ("C:\Program Files\...")
    cmd_quoted = " ".join(f'"{a}"' if (" " in a or "\t" in a) else a for a in args)
    # VBScript escaping: внутренние " → ""
    cmd_vbs = cmd_quoted.replace('"', '""')
    return (
        f"' Auto-generated by ozon-parser service install --mode {mode}\n"
        f"' Remove this file to disable auto-start.\n"
        f"CreateObject(\"WScript.Shell\").Run \"{cmd_vbs}\", 0, False\n"
    )


def _install_windows(
    mode: str,
    *,
    port: int | None,
    interval: float | None,
    log_file: Path | str | None = None,
) -> InstallResult:
    vbs = _win_vbs_path(mode)
    vbs.parent.mkdir(parents=True, exist_ok=True)
    vbs.write_text(
        _win_vbs_content(mode, port=port, interval=interval, log_file=log_file),
        # wscript.exe читает UTF-16 BOM корректно; UTF-8 без BOM
        # превращается в ANSI-мусор при кириллических путях.
        encoding="utf-16",
    )

    # Запустить сейчас, не ждём перезагрузки. wscript.exe — без консоли.
    launched = False
    launch_err = ""
    try:
        subprocess.Popen(
            ["wscript.exe", str(vbs)],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0),
        )
        launched = True
    except Exception as e:
        launch_err = str(e)

    if launched:
        msg = f"vbs written and launched: {vbs}"
    else:
        msg = f"vbs written: {vbs}; launch failed: {launch_err}"
    return InstallResult(
        ok=True, mode=mode, kind="startup-vbs", location=str(vbs), message=msg,
    )


def _uninstall_windows(mode: str) -> UninstallResult:
    vbs = _win_vbs_path(mode)
    if not vbs.exists():
        return UninstallResult(
            ok=True, mode=mode, missing=True,
            message=f"vbs not found: {vbs}",
        )
    try:
        vbs.unlink()
    except OSError as e:
        return UninstallResult(
            ok=False, mode=mode, missing=False, message=f"unlink failed: {e}",
        )
    return UninstallResult(
        ok=True, mode=mode, missing=False, message=f"vbs removed: {vbs}",
    )


def _probe_serve_health(port: int, timeout: float = 0.5) -> bool:
    """GET http://127.0.0.1:<port>/health. True только при 200 + {"ok": true}.

    Проверяет не только HTTP-статус, но и тело: любой чужой процесс
    на порту, отдающий 200, не должен вводить в заблуждение.

    Вынесено в отдельную функцию, чтобы тесты могли её монкипатчить
    без реальной сети и без зависимости от запущенного сервера.
    """
    try:
        with urllib.request.urlopen(
            f"http://127.0.0.1:{int(port)}/health", timeout=timeout
        ) as r:
            if int(getattr(r, "status", 0)) != 200:
                return False
            body = json.loads(r.read().decode("utf-8") or "{}")
            return body.get("ok") is True
    except Exception:
        return False


def _status_windows(mode: str) -> StatusResult:
    vbs = _win_vbs_path(mode)
    installed = vbs.exists()
    if not installed:
        return StatusResult(
            mode=mode, installed=False, running=False,
            message=f"vbs {vbs.name!r} — not installed",
        )
    if mode == "serve":
        try:
            from ozon_parser.config import load_config
            port = load_config().http_port
        except Exception:
            port = 8765
        running = _probe_serve_health(port)
        state = "running" if running else "installed, not responding"
    else:
        # daemon — без HTTP health-check надёжно проверить нельзя.
        # running=False даёт '○ installed' в CLI (честнее, чем ложный ✓).
        running = False
        state = "installed (running state unknown)"
    return StatusResult(
        mode=mode, installed=True, running=running,
        message=f"vbs {vbs.name!r} — {state}",
    )


# ============================================================================
#  Linux: systemd --user
# ============================================================================


def _systemd_unit_dir() -> Path:
    return Path.home() / ".config" / "systemd" / "user"


def _systemd_unit_name(mode: str) -> str:
    return f"ozon-parser-{mode}.service"


def _systemd_unit_content(
    mode: str,
    *,
    port: int | None,
    interval: float | None,
    log_file: Path | str | None = None,
) -> str:
    args = _python_and_args(mode, port=port, interval=interval, log_file=log_file)
    exec_start = " ".join(f'"{a}"' if " " in a else a for a in args)
    return (
        "[Unit]\n"
        f"Description=Ozon Parser ({mode})\n"
        "After=graphical-session.target\n"
        "\n"
        "[Service]\n"
        "Type=simple\n"
        f"ExecStart={exec_start}\n"
        "Restart=on-failure\n"
        "RestartSec=10\n"
        "StandardOutput=journal\n"
        "StandardError=journal\n"
        "\n"
        "[Install]\n"
        "WantedBy=default.target\n"
    )


def _install_linux(
    mode: str,
    *,
    port: int | None,
    interval: float | None,
    log_file: Path | str | None = None,
) -> InstallResult:
    unit_dir = _systemd_unit_dir()
    unit_dir.mkdir(parents=True, exist_ok=True)
    unit_file = unit_dir / _systemd_unit_name(mode)
    unit_file.write_text(
        _systemd_unit_content(mode, port=port, interval=interval, log_file=log_file),
        encoding="utf-8",
    )
    _run(["systemctl", "--user", "daemon-reload"])
    r = _run(["systemctl", "--user", "enable", "--now", _systemd_unit_name(mode)])
    if r.returncode != 0:
        return InstallResult(
            ok=False, mode=mode, kind="systemd", location=str(unit_file),
            message=f"systemctl enable failed ({r.returncode}): {r.stderr.strip() or r.stdout.strip()}",
        )
    return InstallResult(
        ok=True, mode=mode, kind="systemd", location=str(unit_file),
        message=f"unit written and enabled: {unit_file}",
    )


def _uninstall_linux(mode: str) -> UninstallResult:
    unit_file = _systemd_unit_dir() / _systemd_unit_name(mode)
    if not unit_file.exists():
        return UninstallResult(
            ok=True, mode=mode, missing=True, message=f"unit not found: {unit_file}",
        )
    _run(["systemctl", "--user", "disable", "--now", _systemd_unit_name(mode)])
    try:
        unit_file.unlink()
    except OSError as e:
        return UninstallResult(
            ok=False, mode=mode, missing=False, message=f"unlink failed: {e}",
        )
    _run(["systemctl", "--user", "daemon-reload"])
    return UninstallResult(
        ok=True, mode=mode, missing=False, message=f"unit removed: {unit_file}",
    )


def _status_linux(mode: str) -> StatusResult:
    unit_file = _systemd_unit_dir() / _systemd_unit_name(mode)
    installed = unit_file.exists()
    running = False
    if installed:
        r = _run(["systemctl", "--user", "is-active", _systemd_unit_name(mode)])
        running = r.returncode == 0 and (r.stdout or "").strip() == "active"
    return StatusResult(
        mode=mode, installed=installed, running=running,
        message=f"unit {_systemd_unit_name(mode)!r}" + (
            " — active" if running else (" — installed, stopped" if installed else " — not installed")
        ),
    )


# ============================================================================
#  macOS: launchd
# ============================================================================


def _launchd_agents_dir() -> Path:
    return Path.home() / "Library" / "LaunchAgents"


def _launchd_label(mode: str) -> str:
    return f"com.ozon-parser.{mode}"


def _launchd_plist_content(
    mode: str,
    *,
    port: int | None,
    interval: float | None,
    log_file: Path | str | None = None,
) -> str:
    args = _python_and_args(mode, port=port, interval=interval, log_file=log_file)
    args_xml = "\n".join(f"        <string>{_xml_escape(a)}</string>" for a in args)
    log_dir = Path.home() / "Library" / "Logs"
    out_log = log_dir / f"ozon-parser-{mode}.out.log"
    err_log = log_dir / f"ozon-parser-{mode}.err.log"
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" '
        '"http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n'
        '<plist version="1.0">\n'
        '<dict>\n'
        f"    <key>Label</key>\n"
        f"    <string>{_launchd_label(mode)}</string>\n"
        f"    <key>ProgramArguments</key>\n"
        f"    <array>\n{args_xml}\n    </array>\n"
        "    <key>RunAtLoad</key>\n"
        "    <true/>\n"
        "    <key>KeepAlive</key>\n"
        "    <true/>\n"
        f"    <key>StandardOutPath</key>\n    <string>{_xml_escape(str(out_log))}</string>\n"
        f"    <key>StandardErrorPath</key>\n    <string>{_xml_escape(str(err_log))}</string>\n"
        '</dict>\n'
        '</plist>\n'
    )


def _xml_escape(s: str) -> str:
    return (
        str(s)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&apos;")
    )


def _install_macos(
    mode: str,
    *,
    port: int | None,
    interval: float | None,
    log_file: Path | str | None = None,
) -> InstallResult:
    agents = _launchd_agents_dir()
    agents.mkdir(parents=True, exist_ok=True)
    log_dir = Path.home() / "Library" / "Logs"
    log_dir.mkdir(parents=True, exist_ok=True)
    plist = agents / f"{_launchd_label(mode)}.plist"
    plist.write_text(
        _launchd_plist_content(mode, port=port, interval=interval, log_file=log_file),
        encoding="utf-8",
    )
    _run(["launchctl", "unload", str(plist)])
    r = _run(["launchctl", "load", str(plist)])
    if r.returncode != 0:
        return InstallResult(
            ok=False, mode=mode, kind="launchd", location=str(plist),
            message=f"launchctl load failed ({r.returncode}): {r.stderr.strip() or r.stdout.strip()}",
        )
    return InstallResult(
        ok=True, mode=mode, kind="launchd", location=str(plist),
        message=f"plist written and loaded: {plist}",
    )


def _uninstall_macos(mode: str) -> UninstallResult:
    plist = _launchd_agents_dir() / f"{_launchd_label(mode)}.plist"
    if not plist.exists():
        return UninstallResult(
            ok=True, mode=mode, missing=True, message=f"plist not found: {plist}",
        )
    _run(["launchctl", "unload", str(plist)])
    try:
        plist.unlink()
    except OSError as e:
        return UninstallResult(
            ok=False, mode=mode, missing=False, message=f"unlink failed: {e}",
        )
    return UninstallResult(
        ok=True, mode=mode, missing=False, message=f"plist removed: {plist}",
    )


def _status_macos(mode: str) -> StatusResult:
    plist = _launchd_agents_dir() / f"{_launchd_label(mode)}.plist"
    installed = plist.exists()
    running = False
    if installed:
        r = _run(["launchctl", "list", _launchd_label(mode)])
        running = r.returncode == 0
    return StatusResult(
        mode=mode, installed=installed, running=running,
        message=f"label {_launchd_label(mode)!r}" + (
            " — running" if running else (" — installed, stopped" if installed else " — not installed")
        ),
    )


# ============================================================================
#  public API
# ============================================================================


def install(
    mode: str = "serve",
    *,
    port: int | None = None,
    interval: float | None = None,
    log_file: Path | str | None = None,
) -> InstallResult:
    """Устанавливает автозапуск для mode ('serve' | 'daemon')."""
    _validate_mode(mode)
    if sys.platform == "win32":
        return _install_windows(
            mode, port=port, interval=interval, log_file=log_file
        )
    if sys.platform == "darwin":
        return _install_macos(
            mode, port=port, interval=interval, log_file=log_file
        )
    if sys.platform.startswith("linux"):
        return _install_linux(
            mode, port=port, interval=interval, log_file=log_file
        )
    return InstallResult(
        ok=False, mode=mode, kind="unknown", location="",
        message=f"unsupported platform: {sys.platform}",
    )


def uninstall(mode: str = "serve") -> UninstallResult:
    """Удаляет автозапуск. Возвращает ok=True, missing=True если сервиса не было."""
    _validate_mode(mode)
    if sys.platform == "win32":
        return _uninstall_windows(mode)
    if sys.platform == "darwin":
        return _uninstall_macos(mode)
    if sys.platform.startswith("linux"):
        return _uninstall_linux(mode)
    return UninstallResult(
        ok=False, mode=mode, missing=False,
        message=f"unsupported platform: {sys.platform}",
    )


def status(mode: str = "serve") -> StatusResult:
    """Проверяет, установлен ли сервис и запущен ли."""
    _validate_mode(mode)
    if sys.platform == "win32":
        return _status_windows(mode)
    if sys.platform == "darwin":
        return _status_macos(mode)
    if sys.platform.startswith("linux"):
        return _status_linux(mode)
    return StatusResult(
        mode=mode, installed=False, running=False,
        message=f"unsupported platform: {sys.platform}",
    )
